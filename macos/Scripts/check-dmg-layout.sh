#!/bin/zsh
# Gate for a built TypeByVoice DMG: asserts it opens as the designed
# drag-to-install window — app icon on the left, Applications on the right,
# large icons, arrow backdrop — instead of Finder's unstyled defaults.
#
#   ./macos/Scripts/check-dmg-layout.sh macos/dist/TypeByVoice-1.0.0+1.dmg
#   ./macos/Scripts/check-dmg-layout.sh --structural-only <dmg>
#
# Exit 0 only when every assertion passes; otherwise prints one FAIL per
# broken expectation and exits 1.
#
# The semantic assertions read the layout back through Finder, because a
# .DS_Store cannot be inspected any other way: it is a "Bud1" container, not a
# plist (`plutil` refuses it), and the icon geometry inside it has no
# documented byte layout worth parsing. That means they need the same
# Automation permission macOS asks for when package-dmg.sh applies the layout
# (System Settings > Privacy & Security > Automation), from a normal Terminal
# — a sandboxed shell gets "a privilege violation occurred. (-10004)".
# Reading it back briefly opens the volume's Finder window.
#
# Mounted at /Volumes/TypeByVoice, and every other volume of that name detached
# first, because the read-back below addresses the volume BY NAME (Finder has no
# reliable mountpoint-based disk reference). With two volumes named
# TypeByVoice mounted, Finder can resolve `disk "TypeByVoice"` to the wrong one
# and the gate would pass or fail on an older DMG. Reading it back therefore
# opens the volume's Finder window briefly.
set -uo pipefail

VOLUME_NAME="TypeByVoice"
APP_NAME="TypeByVoice.app"
MOUNT_POINT="/Volumes/$VOLUME_NAME"
BACKGROUND=".background/dmg-background.tiff"
# The plan's documented fallback for a Finder that will not scale the HiDPI TIFF.
BACKGROUND_FALLBACK=".background/dmg-background.png"

# Layout constants, matching macos/Scripts/dmg-layout.applescript and the
# backdrop generated by macos/Scripts/make-dmg-background.swift.
EXPECTED_ICON_SIZE=128
EXPECTED_BG_W=540
EXPECTED_BG_H=400
EXPECTED_BG_W2X=1080
EXPECTED_BG_H2X=800
# The window frame dmg-layout.applescript sets: the backdrop canvas plus the
# Finder title bar, so the *content* view is exactly the canvas. One of the four
# original complaints was that the window was too large, so it is asserted.
# (The title bar measured 22pt on the machine this was built on; if a future
# macOS changes it the artwork shifts by the difference, which is a few points.)
EXPECTED_TITLE_BAR=22
EXPECTED_WINDOW="${EXPECTED_BG_W}x$((EXPECTED_BG_H + EXPECTED_TITLE_BAR))"
# Finder's item `position` is the item's centre, and dmg-layout.applescript puts
# both icons on the arrow's centre line, symmetric about the window's centre.
# Positions can come back snapped to Finder's icon grid, so compare with a
# tolerance: 8pt still catches the 50-64pt errors this guards against.
EXPECTED_ICON_Y=212
POSITION_TOLERANCE=8

STRUCTURAL_ONLY=0
if [[ "${1:-}" == "--structural-only" ]]; then
  STRUCTURAL_ONLY=1
  shift
fi

DMG="${1:-}"
if [[ -z "$DMG" || ! -f "$DMG" ]]; then
  echo "usage: check-dmg-layout.sh [--structural-only] <path-to-dmg>" >&2
  exit 2
fi

failures=0
pass() { echo "PASS: $1" }
fail() { echo "FAIL: $1"; failures=$((failures + 1)) }

for stale in /Volumes/$VOLUME_NAME*(N); do
  echo "==> Detaching $stale"
  hdiutil detach "$stale" >/dev/null 2>&1 || rmdir "$stale" 2>/dev/null || true
done

MNT="$MOUNT_POINT"
if ! hdiutil attach "$DMG" -nobrowse -noautoopen -readonly -mountpoint "$MNT" >/dev/null 2>&1; then
  echo "error: could not mount $DMG at $MNT" >&2
  exit 2
fi
trap 'hdiutil detach "$MNT" -force >/dev/null 2>&1 || true; rmdir "$MNT" 2>/dev/null || true' EXIT

echo "==> Checking $(basename "$DMG")"

# --- Structural -------------------------------------------------------------

if [[ -d "$MNT/$APP_NAME" ]]; then
  pass "$APP_NAME present"
else
  fail "$APP_NAME missing from the volume root"
fi

if [[ -L "$MNT/Applications" && "$(readlink "$MNT/Applications")" == "/Applications" ]]; then
  pass "Applications symlink → /Applications"
else
  fail "Applications symlink → /Applications is missing or wrong"
fi

if [[ -s "$MNT/.DS_Store" ]]; then
  pass "volume carries a .DS_Store"
else
  fail ".DS_Store missing — Finder will fall back to alphabetical auto-arrange and its default icon size"
fi

if [[ -s "$MNT/$BACKGROUND" ]]; then
  INFO="$(tiffutil -info "$MNT/$BACKGROUND" 2>/dev/null)"
  IMAGES="$(grep -c '^Directory at' <<<"$INFO" 2>/dev/null || true)"
  # "  Image Width: 540 Image Length: 400" per directory, in order. Both numbers
  # live on the one line, so take the digits rather than relying on awk field
  # numbers (which shift with tiffutil's indentation).
  SIZES=(${(f)"$(grep -E 'Image (Width|Length):' <<<"$INFO" 2>/dev/null | grep -oE '[0-9]+')"})
  if [[ "$IMAGES" == "2" &&
        "${SIZES[1]:-}" == "$EXPECTED_BG_W" && "${SIZES[2]:-}" == "$EXPECTED_BG_H" &&
        "${SIZES[3]:-}" == "$EXPECTED_BG_W2X" && "${SIZES[4]:-}" == "$EXPECTED_BG_H2X" ]]; then
    pass "arrow backdrop is a HiDPI TIFF (${EXPECTED_BG_W}×${EXPECTED_BG_H} + ${EXPECTED_BG_W2X}×${EXPECTED_BG_H2X})"
  else
    fail "backdrop TIFF is not a 1x + 2x pair (got ${IMAGES:-0} image(s): ${SIZES[*]:-none}) — the arrow will be blurred or oversized on a Retina display"
  fi
elif [[ -s "$MNT/$BACKGROUND_FALLBACK" ]]; then
  # The plan's documented fallback: a Finder that will not scale the HiDPI TIFF
  # gets the 1x PNG instead. Accept it, at the layout size.
  # Filter to sips's own pixel lines first: sips prints the file path ahead of
  # them, and the path carries digits of its own.
  SIZES=(${(f)"$(sips -g pixelWidth -g pixelHeight "$MNT/$BACKGROUND_FALLBACK" 2>/dev/null | grep -E 'pixel(Width|Height):' | grep -oE '[0-9]+')"})
  if [[ "${SIZES[1]:-}" == "$EXPECTED_BG_W" && "${SIZES[2]:-}" == "$EXPECTED_BG_H" ]]; then
    pass "arrow backdrop is the 1x PNG fallback (${EXPECTED_BG_W}×${EXPECTED_BG_H}; Retina will upscale it)"
  else
    fail "backdrop PNG is ${SIZES[*]:-unreadable}, expected ${EXPECTED_BG_W}×${EXPECTED_BG_H}"
  fi
else
  fail "$BACKGROUND missing — the window has no arrow"
fi

for key in TBV_API_URL TBV_DICTATE_URL; do
  value="$(plutil -extract "$key" raw "$MNT/$APP_NAME/Contents/Info.plist" 2>/dev/null)"
  if [[ -n "$value" ]]; then
    pass "$key baked into Info.plist"
  else
    fail "$key missing from the packaged Info.plist"
  fi
done

# --- Semantic (needs Automation permission) ---------------------------------

if [[ $STRUCTURAL_ONLY -eq 1 ]]; then
  echo "==> Skipping the Finder read-back (--structural-only)"
else
  READBACK="$(osascript -e '
on run a
	set volName to item 1 of a
	tell application "Finder"
		tell disk (volName as text)
			open
			delay 1
			set v to icon view options of container window
			set p1 to position of item "TypeByVoice.app" of container window
			set p2 to position of item "Applications" of container window
			set b to bounds of container window
			set out to ((icon size of v) as text) & "|" & ((arrangement of v) as text) & "|" & (((background picture of v) is missing value) as text) & "|" & ((item 1 of p1) as text) & "," & ((item 2 of p1) as text) & "|" & ((item 1 of p2) as text) & "," & ((item 2 of p2) as text) & "|" & (((item 3 of b) - (item 1 of b)) as text) & "x" & (((item 4 of b) - (item 2 of b)) as text)
			close
			return out
		end tell
	end tell
end run' "$VOLUME_NAME" 2>&1)"

  if [[ "$READBACK" != *"|"* ]]; then
    fail "could not read the layout back through Finder: $READBACK"
    echo "      fix: allow Finder automation for this app (System Settings > Privacy & Security"
    echo "           > Automation) and run this from a normal Terminal window — a sandboxed"
    echo "           shell is refused with 'a privilege violation occurred. (-10004)'."
    echo "           --structural-only runs the checks that do not need Finder."
  else
    IFS='|' read -r icon_size arrangement bg_missing p1 p2 win_size <<<"$READBACK"
    app_x="${${p1%%,*}//[^0-9-]/}"
    app_y="${${p1##*,}//[^0-9-]/}"
    folder_x="${${p2%%,*}//[^0-9-]/}"
    folder_y="${${p2##*,}//[^0-9-]/}"

    if [[ "$icon_size" == "$EXPECTED_ICON_SIZE" ]]; then
      pass "icon size is $EXPECTED_ICON_SIZE"
    else
      fail "icon size is $icon_size, expected $EXPECTED_ICON_SIZE — the icons will look small"
    fi

    if [[ "$win_size" == "$EXPECTED_WINDOW" ]]; then
      pass "window is $EXPECTED_WINDOW"
    else
      fail "window is $win_size, expected $EXPECTED_WINDOW (both numbers are points)"
    fi

    # Balanced about the window's centre, and both on the arrow's line. "The app
    # is left of Applications" alone passes on a pair that sits 50pt off to one
    # side with the arrow overlapping the folder, which is what the first
    # shipped attempt did.
    if [[ -n "$app_x" && -n "$folder_x" && "$win_size" == *x* ]]; then
      midpoint=$(( (app_x + folder_x) / 2 ))
      centre=$(( ${win_size%%x*} / 2 ))
      delta=$(( midpoint - centre ))
      (( delta < 0 )) && delta=$(( -delta ))
      if (( delta <= POSITION_TOLERANCE )); then
        pass "icon pair is balanced about the window centre (midpoint $midpoint vs centre $centre)"
      else
        fail "icon pair is off-centre: midpoint $midpoint vs window centre $centre (${delta}pt out) — the arrow lands asymmetrically between the icons"
      fi
    fi

    for entry in "app:$app_y" "Applications:$folder_y"; do
      icon_y="${entry##*:}"
      [[ -n "$icon_y" ]] || continue
      dy=$(( icon_y - EXPECTED_ICON_Y ))
      (( dy < 0 )) && dy=$(( -dy ))
      if (( dy <= POSITION_TOLERANCE )); then
        pass "${entry%%:*} icon sits on the arrow's line (y $icon_y)"
      else
        fail "${entry%%:*} icon is at y $icon_y, expected $EXPECTED_ICON_Y — it floats off the arrow's line"
      fi
    done

    if [[ "$arrangement" == "not arranged" ]]; then
      pass "auto-arrange is off, so the recorded icon positions hold"
    else
      fail "arrangement is '$arrangement', expected 'not arranged' — Finder will re-place the icons"
    fi

    if [[ "$bg_missing" == "false" ]]; then
      pass "background picture is set"
    else
      fail "background picture is not set (got missing value)"
    fi

    if [[ -n "$app_x" && -n "$folder_x" && "$app_x" -lt "$folder_x" ]]; then
      pass "app icon is left of Applications ($app_x < $folder_x)"
    else
      fail "app icon is not left of Applications (got app x=$app_x at $p1, Applications x=$folder_x at $p2)"
    fi
  fi
fi

# --- Result -----------------------------------------------------------------

if (( failures > 0 )); then
  echo "==> ${failures} assertion(s) failed"
  exit 1
fi
echo "==> all assertions passed"
